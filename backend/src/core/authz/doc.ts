import {
  ALL_PERMISSIONS,
  PERMISSION_DESCRIPTIONS,
  PERMISSION_GROUPS,
  type Permission,
  type PermissionGroup,
} from './catalog';
import { ACCOUNT_ROLE_PERMISSIONS, PARTICIPATION_PERMISSIONS } from './roles';
import type { RouteDeclaration } from './route-policy';

export interface DocRoute {
  method: string;
  url: string;
  config: RouteDeclaration | undefined;
}

const COLUMNS = [
  ['platform_admin', 'platform admin'],
  ['institution_admin', 'institution admin'],
  ['member', 'member'],
] as const;
const PARTICIPATIONS = ['instructor', 'assistant', 'learner'] as const;

const mark = (yes: boolean) => (yes ? 'yes' : '');

function authLabel(c: RouteDeclaration | undefined): string {
  if (c?.public === true) return 'public';
  if (c?.authenticated === true) return 'any signed-in user';
  const p = c?.permission;
  if (p === undefined) return 'UNDECLARED';
  const names = (typeof p === 'string' ? [p] : [...p]).map((x) => `\`${x}\``).join(' or ');
  return c?.scope === 'offering' ? `${names} in the offering` : names;
}

/**
 * docs/permissions.md, generated from the code (catalog, role maps and the registered routes) so it
 * can never drift: `pnpm docs:permissions` writes it, and a test + CI fail when the committed file
 * differs from this output.
 */
export function renderPermissionsDoc(routes: readonly DocRoute[]): string {
  const out: string[] = [];
  out.push('# Permissions');
  out.push('');
  out.push(
    '> GENERATED by `pnpm docs:permissions` from `backend/src/core/authz` and the registered routes.',
  );
  out.push('> Do not edit by hand: a test and CI fail when this file is out of date.');
  out.push('');
  out.push(
    'Authorization is checked by **permission name** with `can(subject, permission, resource?)`: deny by default, ' +
      'pure and synchronous for account-level checks (no database). Route checks are coarse; ' +
      'services re-check resource-level permissions and are the source of truth.',
  );
  out.push('');
  out.push('## Who can do what');
  out.push('');
  out.push(
    'Account roles are `platform_admin` (admin host only), `institution_admin` and `member` (tenant host). ' +
      'Course roles come from a participation in a course (`instructor`, `assistant`, `learner`) that the caller resolves ' +
      'and passes to `can()`.',
  );
  out.push('');
  const head = [
    'Permission',
    ...COLUMNS.map(([, label]) => label),
    ...PARTICIPATIONS.map((p) => `course: ${p}`),
    'Description',
  ];
  out.push(`| ${head.join(' | ')} |`);
  out.push(`|${head.map(() => '---').join('|')}|`);
  for (const group of Object.keys(PERMISSION_GROUPS) as PermissionGroup[]) {
    out.push(`| **${group}** |${' |'.repeat(head.length - 1)}`);
    for (const p of PERMISSION_GROUPS[group] as readonly Permission[]) {
      const cells = [
        `\`${p}\``,
        ...COLUMNS.map(([role]) => mark(ACCOUNT_ROLE_PERMISSIONS[role].has(p))),
        ...PARTICIPATIONS.map((k) => {
          if (!PARTICIPATION_PERMISSIONS[k].has(p)) return '';
          return p === 'grade.view_own' ? 'own only' : 'yes';
        }),
        PERMISSION_DESCRIPTIONS[p],
      ];
      out.push(`| ${cells.join(' | ')} |`);
    }
  }
  out.push('');
  out.push(`${ALL_PERMISSIONS.length} permissions. Notes:`);
  out.push('');
  out.push(
    '- An institution admin has read-only `content.view` on every course of the college but edits, publishes, ' +
      'creates assessments and grades only as a participant of that course.',
  );
  out.push(
    '- "in the offering": the permission comes from the caller\'s participation in that offering (instructor, assistant or learner), ' +
      'or, for read access, from an account-level permission. The route only requires a session; the service answers 404 to a ' +
      'member who does not participate (offerings cannot be enumerated) and 403 to a participant without the permission.',
  );
  out.push(
    '- A session belongs to one host: a platform admin cannot act on a tenant host, and tenant users cannot act on the admin host.',
  );
  out.push('');
  out.push('## Routes');
  out.push('');
  out.push(
    'Every route declares exactly one of `config.permission`, `config.authenticated` or `config.public` ' +
      '(the app refuses to start otherwise).',
  );
  out.push('');
  out.push('| Method | Path | Authorization |');
  out.push('|---|---|---|');
  const sorted = [...routes].sort(
    (a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method),
  );
  for (const r of sorted) out.push(`| ${r.method} | \`${r.url}\` | ${authLabel(r.config)} |`);
  out.push('');
  return out.join('\n');
}
